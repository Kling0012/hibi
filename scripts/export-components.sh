#!/usr/bin/env bash
# Export the private hibi-server and hibi-memory snapshots into this
# repository as server/ and memory/. No git history crosses over: the trees
# are taken from the source repositories' HEAD via `git archive`.
#
# The sources are only read, never modified. Everything is staged in a temp
# directory and audited for private strings; only a clean audit is swapped
# into the repository, so a failed run leaves server/ and memory/ untouched.
# The tree they replace, if any, is kept under the temp directory printed at
# the end (it lives in /tmp and goes away on reboot).
#
# Usage:
#   scripts/export-components.sh --exemplar FILE \
#     [--server-src DIR] [--memory-src DIR]
#
#   --server-src  private hibi-server checkout (default: ../hibi-server,
#                 a sibling of this repository)
#   --memory-src  private hibi-memory checkout (default: ../hibi-memory-pub)
#   --exemplar    public replacement for server/app/blog_exemplar.md.
#                 Required: the in-repo exemplar is a personal diary.
#
# Explicit DIR paths resolve from the current directory; defaults resolve
# from the repository root.

set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)

SERVER_SRC=$(realpath -m "$ROOT/../hibi-server")
MEMORY_SRC=$(realpath -m "$ROOT/../hibi-memory-pub")
EXEMPLAR=

while [ $# -gt 0 ]; do
  case $1 in
    --server-src) SERVER_SRC=$(realpath -m "$2"); shift 2 ;;
    --memory-src) MEMORY_SRC=$(realpath -m "$2"); shift 2 ;;
    --exemplar)   EXEMPLAR=$2; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

die() { echo "export-components: $*" >&2; exit 1; }

[ -n "$EXEMPLAR" ] || die "--exemplar FILE is required (public blog exemplar)"
[ -f "$EXEMPLAR" ] || die "exemplar not found: $EXEMPLAR"

for d in "$SERVER_SRC" "$MEMORY_SRC"; do
  git -C "$d" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || die "not a git checkout: $d"
done
SERVER_SHA=$(git -C "$SERVER_SRC" rev-parse --short HEAD)
SERVER_BRANCH=$(git -C "$SERVER_SRC" branch --show-current)
MEMORY_SHA=$(git -C "$MEMORY_SRC" rev-parse --short HEAD)
MEMORY_BRANCH=$(git -C "$MEMORY_SRC" branch --show-current)

# Private strings that must never appear in the exported trees. Explanatory
# placeholders (100.x.y.z, <your-server>) do not match.
AUDIT_PATTERN='100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\.[0-9]+\.[0-9]+|ts\.net|@gmail'

TMP=$(mktemp -d /tmp/hibi-export.XXXXXX)
trap 'echo "export-components: staging (and any replaced tree) kept at $TMP" >&2' EXIT

# --- server/ : full tree of hibi-server HEAD, minus repro/CI leftovers ------
mkdir "$TMP/server"
git -C "$SERVER_SRC" archive --format=tar HEAD \
  | tar -x -C "$TMP/server" \
      --exclude='scripts/repro_issue_*' \
      --exclude='scripts/*repro*' \
      --exclude='scripts/regression_issue*' \
      --exclude='docs/repro-issue-*.md' \
      --exclude='docs/*repro*' \
      --exclude='.github' \
      --exclude='.github/*'

shopt -s nullglob
leftover=("$TMP/server"/scripts/*repro* "$TMP/server"/scripts/regression_issue* "$TMP/server"/docs/*repro*)
shopt -u nullglob
[ ${#leftover[@]} -eq 0 ] || die "exclusion failed: ${leftover[*]}"
[ ! -e "$TMP/server/.github" ] || die "exclusion failed: $TMP/server/.github"

[ -f "$TMP/server/app/blog_exemplar.md" ] \
  || die "server tree has no app/blog_exemplar.md (upstream layout change?)"
cp "$EXEMPLAR" "$TMP/server/app/blog_exemplar.md"

cat > "$TMP/server/EXPORTED_FROM" <<EOF
# Generated by scripts/export-components.sh - do not edit.
source: hibi-server (private repository), branch ${SERVER_BRANCH}
commit: ${SERVER_SHA}
EOF

# --- memory/ : only the files matching PUBLIC_FILES -------------------------
PUBLIC_FILES=$MEMORY_SRC/PUBLIC_FILES
[ -f "$PUBLIC_FILES" ] || die "PUBLIC_FILES not found in --memory-src"

mapfile -t patterns < <(sed -e 's/[[:space:]]*#.*$//' -e '/^[[:space:]]*$/d' "$PUBLIC_FILES")
[ ${#patterns[@]} -gt 0 ] || die "PUBLIC_FILES contains no patterns"

matched=()
while IFS= read -r -d '' f; do
  for p in "${patterns[@]}"; do
    if [[ $f == $p ]]; then matched+=("$f"); break; fi
  done
done < <(git -C "$MEMORY_SRC" ls-files -z)
[ ${#matched[@]} -gt 0 ] || die "no tracked files in --memory-src match PUBLIC_FILES"

mkdir "$TMP/memory"
git -C "$MEMORY_SRC" archive --format=tar HEAD -- "${matched[@]}" \
  | tar -x -C "$TMP/memory"
for f in "${matched[@]}"; do
  [ -f "$TMP/memory/$f" ] || die "git archive did not produce $f"
done

cat > "$TMP/memory/EXPORTED_FROM" <<EOF
# Generated by scripts/export-components.sh - do not edit.
source: hibi-memory (private repository), branch ${MEMORY_BRANCH}
commit: ${MEMORY_SHA}
EOF

# --- audit before touching the repository -----------------------------------
set +e
grep -rnIE "$AUDIT_PATTERN" "$TMP/server" "$TMP/memory"
audit_rc=$?
set -e
if [ "$audit_rc" -eq 0 ]; then
  die "audit FAILED: private strings found (listed above); server/ and memory/ left untouched"
elif [ "$audit_rc" -ne 1 ]; then
  die "audit grep failed with rc=$audit_rc"
fi
echo "audit: clean (0 hits)"

# --- swap the audited trees into place ---------------------------------------
mkdir "$TMP/previous"
for d in server memory; do
  if [ -e "$ROOT/$d" ]; then mv "$ROOT/$d" "$TMP/previous/$d"; fi
  mv "$TMP/$d" "$ROOT/$d"
done

echo "exported:"
echo "  server/ : $(find "$ROOT/server" -type f | wc -l) files  <- hibi-server ${SERVER_BRANCH} @ ${SERVER_SHA}"
echo "  memory/ : $(find "$ROOT/memory" -type f | wc -l) files  <- hibi-memory ${MEMORY_BRANCH} @ ${MEMORY_SHA}"
