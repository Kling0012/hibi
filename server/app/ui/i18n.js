// 多言語対応（ja / en / zh 簡体字）。管理画面とブログの両方から使う共用モジュール。
// 言語の決定: URL の ?lang= → localStorage["mc.lang"] → navigator.language（ja*→ja, zh*→zh, 他→en）
export const LANGS = { ja: "日本語", en: "English", zh: "中文" };
export const LOCALE = { ja: "ja-JP", en: "en-US", zh: "zh-CN" };

const store = {
  get(k) { try { return localStorage.getItem(k); } catch { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch {} },
};

function detectLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (LANGS[q]) return q;
  const saved = store.get("mc.lang");
  if (LANGS[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("zh")) return "zh";
  return "en";
}

